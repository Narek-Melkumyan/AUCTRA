import type { CatalogLot } from './catalog.js';

type V = NonNullable<CatalogLot['vehicle']>;
const car = (
  key: string,
  file: string,
  sub: 'cars-supercars' | 'cars-classic' | 'cars-modern',
  title: string,
  description: string,
  o: Pick<
    CatalogLot,
    'condition' | 'city' | 'country' | 'start' | 'increment' | 'plan' | 'hours'
  > &
    Partial<Pick<CatalogLot, 'reserve' | 'days' | 'bids' | 'antiSniping'>> & {
      v: V;
      engine?: string;
      seller?: CatalogLot['seller'];
    },
): CatalogLot => ({
  key: `car-${key}`,
  file: `File:${file}`,
  category: 'cars',
  subcategory: sub,
  seller: o.seller ?? 'northgate',
  title,
  description,
  condition: o.condition,
  city: o.city,
  country: o.country,
  start: o.start,
  increment: o.increment,
  ...(o.reserve ? { reserve: o.reserve } : {}),
  plan: o.plan,
  hours: o.hours,
  ...(o.days ? { days: o.days } : {}),
  ...(o.bids ? { bids: o.bids } : {}),
  ...(o.antiSniping ? { antiSniping: true } : {}),
  attributes: {
    title_status: 'Clean',
    service_history: true,
    ...(o.engine ? { engine: o.engine } : {}),
  },
  vehicle: o.v,
});

type W = NonNullable<CatalogLot['watch']>;
const watch = (
  key: string,
  file: string,
  sub: 'watches-sport' | 'watches-dress' | 'watches-vintage',
  title: string,
  description: string,
  o: Pick<
    CatalogLot,
    'condition' | 'city' | 'country' | 'start' | 'increment' | 'plan' | 'hours'
  > &
    Partial<Pick<CatalogLot, 'reserve' | 'days' | 'bids'>> & {
      w: W;
      wr?: number;
      seller?: CatalogLot['seller'];
    },
): CatalogLot => ({
  key: `watch-${key}`,
  file: `File:${file}`,
  category: 'watches',
  subcategory: sub,
  seller: o.seller ?? 'meridian',
  title,
  description,
  condition: o.condition,
  city: o.city,
  country: o.country,
  start: o.start,
  increment: o.increment,
  ...(o.reserve ? { reserve: o.reserve } : {}),
  plan: o.plan,
  hours: o.hours,
  ...(o.days ? { days: o.days } : {}),
  ...(o.bids ? { bids: o.bids } : {}),
  attributes: o.wr ? { water_resistance_m: o.wr } : {},
  watch: o.w,
});

type Base = Pick<
  CatalogLot,
  'condition' | 'city' | 'country' | 'start' | 'increment' | 'plan' | 'hours'
> &
  Partial<
    Pick<CatalogLot, 'reserve' | 'days' | 'bids' | 'seller' | 'subcategory'>
  > & {
    attributes: CatalogLot['attributes'];
  };
const lot =
  (category: string, prefix: string, seller: CatalogLot['seller']) =>
  (
    key: string,
    file: string,
    title: string,
    description: string,
    o: Base,
  ): CatalogLot => ({
    key: `${prefix}-${key}`,
    file: `File:${file}`,
    category,
    ...(o.subcategory ? { subcategory: o.subcategory } : {}),
    seller: o.seller ?? seller,
    title,
    description,
    condition: o.condition,
    city: o.city,
    country: o.country,
    start: o.start,
    increment: o.increment,
    ...(o.reserve ? { reserve: o.reserve } : {}),
    plan: o.plan,
    hours: o.hours,
    ...(o.days ? { days: o.days } : {}),
    ...(o.bids ? { bids: o.bids } : {}),
    attributes: o.attributes,
  });
