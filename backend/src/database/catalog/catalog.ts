/**
 * AUCTRA demonstration catalogue. Every lot is fictional demo data (labelled as such in its
 * description and in the UI) illustrated with a freely licensed photo from Wikimedia
 * Commons. Each title describes what the photo actually shows; works whose originals are in
 * museums are offered as reproductions or later editions, never as the original.
 *
 * `plan` decides the lot's lifecycle when it is first seeded:
 *   live      – bidding open now, ends `hours` from seeding
 *   upcoming  – starts `hours` from seeding, runs `days`
 *   sold      – bidding happens at seed time through the real bid engine, then it closes
 *   unsold    – closes without meeting its reserve (or without bids)
 * `bids` = number of bids placed by demo buyer accounts through the real bidding service.
 */
import type { ItemCondition } from '../../generated/prisma/client.js';

export type SellerKey =
  | 'northgate'
  | 'meridian'
  | 'larkspur'
  | 'atelier'
  | 'harbourline'
  | 'curio'
  | 'private';

export interface CatalogLot {
  key: string;
  /** Wikimedia Commons file page title, e.g. "File:Ferrari 458 Italia, Toulouse.jpg". */
  file: string;
  category: string;
  /** Optional: some lots (e.g. bracelets, brooches) have no matching subcategory. */
  subcategory?: string;
  seller: SellerKey;
  title: string;
  description: string;
  condition: ItemCondition;
  city: string;
  country: string;
  /** Prices in whole US dollars. */
  start: number;
  increment: number;
  reserve?: number;
  buyNow?: number;
  plan: 'live' | 'upcoming' | 'sold' | 'unsold';
  /** live: hours until the end; upcoming: hours until the start. */
  hours: number;
  /** Duration in days for upcoming lots (default 5). */
  days?: number;
  bids?: number;
  antiSniping?: boolean;
  attributes: Record<string, string | number | boolean>;
  vehicle?: {
    make: string;
    model: string;
    year: number;
    mileageKm?: number;
    transmission?: string;
    fuelType?: string;
    exteriorColor?: string;
    bodyStyle?: string;
  };
  watch?: {
    brand: string;
    model: string;
    referenceNumber?: string;
    year?: number;
    caseMaterial?: string;
    caseDiameterMm?: number;
    movement?: string;
    hasBox?: boolean;
    hasPapers?: boolean;
  };
}

