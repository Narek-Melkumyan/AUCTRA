import { randomUUID } from 'node:crypto';
import { HttpStatus, Injectable, Logger } from '@nestjs/common';
import { Prisma } from '../generated/prisma/client.js';
import { PrismaService, type Tx } from '../prisma/prisma.service.js';
import { AppConfig } from '../config/app-config.js';
import { MetricsService } from '../metrics/metrics.service.js';
import { StorageService } from '../storage/storage.service.js';
import { IMMUTABLE_CACHE_CONTROL } from '../storage/storage.types.js';
import { AuctionsService } from '../auctions/auctions.service.js';
import { AuditService } from '../audit/audit.service.js';
import { isRestricted, type AuthContext } from '../common/auth-context.js';
import { AppError, Errors } from '../common/errors.js';
import { Permission } from '../roles/permissions.js';
import {
  ProcessingQueue,
  VARIANTS,
  processImage,
  type ProcessedImage,
} from './image-processor.js';
import {
  toImageDto,
  type ImageDto,
  type StoredVariants,
} from './media.mapper.js';

/** An upload that has not committed within this window is treated as abandoned. */
const PENDING_UPLOAD_TTL_MS = 15 * 60_000;
const OUTPUT_MIME = 'image/webp';

/** `[namespace/]auctions/{auctionId}/{imageId}/` — always generated by the server. */
export const keyPrefixFor = (
  auctionId: string,
  imageId: string,
  namespace = '',
) => `${namespace ? `${namespace}/` : ''}auctions/${auctionId}/${imageId}/`;
export const variantKeys = (prefix: string) =>
  VARIANTS.map((v) => `${prefix}${v.name}.webp`);

export interface UploadedFile {
  buffer: Buffer;
  originalname: string;
  size: number;
}

export interface UploadOutcome {
  images: ImageDto[];
  uploaded: ImageDto[];
  failed: { index: number; fileName: string; code: string; message: string }[];
}

interface Access {
  auctionId: string;
  asAdmin: boolean;
}

/**
 * Listing image management.
 *
 * Upload pipeline (no database transaction is held during processing or network I/O):
 *   1. authorise (owner of a DRAFT, or a moderator) and check the image limit
 *   2. validate + encode WebP variants with Sharp, in a bounded queue
 *   3. record a cleanup task for the new key prefix (the crash-safety net)
 *   4. upload the variants to object storage
 *   5. short transaction: re-check, insert the row, remove the cleanup task
 * Any failure after step 3 deletes what was uploaded; if that delete also fails, the
 * cleanup task stays and MediaCleanupWorker retries it. Existing images are only removed
 * after their replacement has committed.
 */
@Injectable()
export class AuctionImagesService {
  private readonly logger = new Logger(AuctionImagesService.name);
  readonly queue: ProcessingQueue;

  constructor(
    private readonly prisma: PrismaService,
    private readonly config: AppConfig,
    private readonly storage: StorageService,
    private readonly metrics: MetricsService,
    private readonly auctions: AuctionsService,
    private readonly audit: AuditService,
  ) {
    this.queue = new ProcessingQueue(
      config.mediaProcessingConcurrency,
      config.mediaProcessingQueueMax,
    );
  }

  // ───────────── Access ─────────────

  /**
   * Owners may manage images while the listing is a DRAFT (the same rule as editing the
   * listing). Moderators may manage images of any listing. Everyone else gets 404, so
   * the existence of other people's drafts is not revealed.
   */
  async assertCanManage(
    auth: AuthContext,
    auctionId: string,
    tx: Tx | PrismaService = this.prisma,
  ): Promise<Access> {
    const a = await tx.auction.findUnique({
      where: { id: auctionId },
      select: { sellerId: true, status: true },
    });
    if (!a) throw Errors.notFound('Auction');
    const asAdmin = auth.permissions.has(Permission.AUCTION_MODERATE);
    const isOwner =
      a.sellerId === auth.userId &&
      auth.permissions.has(Permission.AUCTION_MANAGE_OWN);
    if (!asAdmin && !isOwner) throw Errors.notFound('Auction');
    if (!asAdmin) {
      if (isRestricted(auth))
        throw Errors.forbidden('Your account is restricted.');
      if (a.status !== 'DRAFT')
        throw Errors.conflict(
          'AUCTION_NOT_EDITABLE',
          'Photos can only be changed while the listing is a draft. Withdraw it from review first.',
        );
    }
    return { auctionId, asAdmin };
  }

  // ───────────── Reads ─────────────

  /** Same visibility rules as GET /auctions/:id. */
  async list(auctionId: string, auth?: AuthContext): Promise<ImageDto[]> {
    const a = await this.auctions.get(auctionId, auth);
    return a.media;
  }

  private async rows(auctionId: string, tx: Tx | PrismaService = this.prisma) {
    return tx.listingMedia.findMany({
      where: { auctionId },
      orderBy: { position: 'asc' },
    });
  }

  private async dtos(auctionId: string) {
    return (await this.rows(auctionId)).map(toImageDto);
  }

  // ───────────── Upload / replace ─────────────

  async upload(
    auth: AuthContext,
    auctionId: string,
    files: UploadedFile[],
    altText?: string,
  ): Promise<UploadOutcome> {
    if (!files.length)
      throw Errors.badRequest(
        'NO_FILES',
        'Attach at least one image in the "images" field.',
      );
    const access = await this.assertCanManage(auth, auctionId);
    const count = await this.prisma.listingMedia.count({
      where: { auctionId },
    });
    const max = this.config.mediaMaxImagesPerAuction;
    if (count >= max)
      throw Errors.conflict(
        'IMAGE_LIMIT_REACHED',
        `A listing can have at most ${max} photos.`,
        { max },
      );

    const uploaded: ImageDto[] = [];
    const failed: UploadOutcome['failed'] = [];
    // Sequential: one file's buffers are released before the next is decoded.
    for (const [index, file] of files.entries()) {
      try {
        uploaded.push(
          await this.storeOne(auth, access, file, { altText: altText ?? null }),
        );
      } catch (err) {
        if (!(err instanceof AppError)) throw err;
        const body = err.getResponse() as { code: string; message: string };
        failed.push({
          index,
          fileName: displayName(file.originalname),
          code: body.code,
          message: body.message,
        });
        // A single-file request reports its error with the proper status code.
        if (files.length === 1) throw err;
      }
    }
    if (!uploaded.length) {
      const first = failed[0]!;
      throw Errors.unprocessable(first.code, first.message, { failed });
    }
    return { images: await this.dtos(auctionId), uploaded, failed };
  }

  async replace(
    auth: AuthContext,
    auctionId: string,
    imageId: string,
    file: UploadedFile | undefined,
  ): Promise<{ images: ImageDto[]; image: ImageDto }> {
    if (!file)
      throw Errors.badRequest(
        'NO_FILES',
        'Attach the replacement image in the "images" field.',
      );
    const access = await this.assertCanManage(auth, auctionId);
    const old = await this.prisma.listingMedia.findFirst({
      where: { id: imageId, auctionId },
      select: { id: true, altText: true },
    });
    if (!old) throw Errors.notFound('Image');
    const image = await this.storeOne(auth, access, file, {
      replaceId: imageId,
      altText: old.altText,
    });
    return { images: await this.dtos(auctionId), image };
  }

  private async storeOne(
    auth: AuthContext,
    access: Access,
    file: UploadedFile,
    opts: { replaceId?: string; altText: string | null },
  ): Promise<ImageDto> {
    const { auctionId } = access;
    const started = performance.now();
    let processed: ProcessedImage;
    try {
      processed = await this.queue.run(() =>
        processImage(file.buffer, {
          maxBytes: this.config.mediaMaxUploadBytes,
          maxPixels: this.config.mediaMaxPixels,
        }),
      );
    } catch (err) {
      this.metrics.mediaUploads.inc({ result: 'rejected' });
      throw err;
    }
    this.metrics.mediaProcessing.observe((performance.now() - started) / 1000);

    await this.assertNotDuplicate(
      auctionId,
      processed.contentHash,
      opts.replaceId,
    );

    const imageId = randomUUID();
    const prefix = keyPrefixFor(auctionId, imageId, this.config.mediaKeyPrefix);
    const provider = this.storage.provider;
    const now = await this.prisma.dbNow();
    await this.prisma.mediaCleanupTask.create({
      data: {
        storage: provider,
        keyPrefix: prefix,
        reason: 'upload_pending',
        runAfter: new Date(now.getTime() + PENDING_UPLOAD_TTL_MS),
      },
    });

    const variants = {} as StoredVariants;
    try {
      // allSettled, not all: on failure every in-flight upload must finish before the
      // cleanup runs, otherwise a late PUT could land after the DELETE and leave an orphan.
      const results = await Promise.allSettled(
        processed.variants.map(async (v) => {
          const key = `${prefix}${v.name}.webp`;
          await this.storage.put(key, v.data, {
            contentType: OUTPUT_MIME,
            cacheControl: IMMUTABLE_CACHE_CONTROL,
            metadata: {
              'auction-id': auctionId,
              'image-id': imageId,
              variant: v.name,
            },
          });
          variants[v.name] = {
            key,
            url: this.storage.publicUrl(key),
            width: v.width,
            height: v.height,
            bytes: v.bytes,
          };
        }),
      );
      const failed = results.find(
        (r): r is PromiseRejectedResult => r.status === 'rejected',
      );
      if (failed) throw failed.reason;
    } catch (err) {
      this.metrics.mediaUploads.inc({ result: 'storage_error' });
      this.logger.error({
        msg: 'image upload to storage failed',
        auctionId,
        imageId,
        provider,
        error: (err as Error).name,
      });
      await this.cleanupNow(prefix, provider, 'upload_failed');
      throw new AppError(
        HttpStatus.BAD_GATEWAY,
        'MEDIA_UPLOAD_FAILED',
        'The image could not be stored. Nothing was changed — please try again.',
      );
    }

    const full = processed.variants.find((v) => v.name === 'full')!;
    let replacedPrefix: string | null = null;
    let row;
    try {
      row = await this.prisma.$transaction(async (tx) => {
        await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtextextended(${`media:${auctionId}`}, 0))`;
        // Re-check: the listing may have been submitted or deleted while we uploaded.
        await this.assertCanManage(auth, auctionId, tx);
        const existing = await this.rows(auctionId, tx);
        let position = existing.length
          ? Math.max(...existing.map((m) => m.position)) + 1
          : 0;
        let isPrimary = existing.length === 0;
        if (opts.replaceId) {
          const target = existing.find((m) => m.id === opts.replaceId);
          if (!target) throw Errors.notFound('Image');
          position = target.position;
          isPrimary = target.isPrimary;
          await tx.listingMedia.delete({ where: { id: target.id } });
          if (target.storageKeyPrefix) {
            replacedPrefix = target.storageKeyPrefix;
            await this.scheduleCleanup(
              tx,
              target.storageKeyPrefix,
              target.storage as 'R2' | 'LOCAL',
              'image_replaced',
            );
          }
        } else if (existing.length >= this.config.mediaMaxImagesPerAuction) {
          throw Errors.conflict(
            'IMAGE_LIMIT_REACHED',
            `A listing can have at most ${this.config.mediaMaxImagesPerAuction} photos.`,
            { max: this.config.mediaMaxImagesPerAuction },
          );
        }
        const created = await tx.listingMedia.create({
          data: {
            id: imageId,
            auctionId,
            type: 'IMAGE',
            url: variants.full.url,
            altText: opts.altText,
            width: full.width,
            height: full.height,
            position,
            isPrimary,
            storage: provider,
            storageKeyPrefix: prefix,
            variants: variants as unknown as Prisma.InputJsonValue,
            mimeType: OUTPUT_MIME,
            bytes: processed.variants.reduce((n, v) => n + v.bytes, 0),
            originalMimeType: processed.inputMime,
            originalBytes: processed.inputBytes,
            contentHash: processed.contentHash,
            uploadedById: auth.userId,
          },
        });
        // Claim the pending-upload task. If the sweeper already claimed it (attempts > 0)
        // it may be deleting these objects, so this upload must not commit.
        const claimed = await tx.mediaCleanupTask.deleteMany({
          where: { keyPrefix: prefix, attempts: 0 },
        });
        if (claimed.count !== 1)
          throw Errors.unavailable(
            'MEDIA_UPLOAD_EXPIRED',
            'The upload took too long. Please try again.',
          );
        await this.audit.record(
          {
            actorId: auth.userId,
            action: opts.replaceId
              ? 'auction.image.replace'
              : 'auction.image.upload',
            entityType: 'auction',
            entityId: auctionId,
            metadata: {
              imageId,
              ...(opts.replaceId ? { replacedImageId: opts.replaceId } : {}),
              ...(access.asAdmin ? { asAdmin: true } : {}),
            },
          },
          tx,
        );
        return created;
      });
    } catch (err) {
      this.metrics.mediaUploads.inc({ result: 'db_error' });
      await this.cleanupNow(prefix, provider, 'upload_failed');
      if (
        err instanceof Prisma.PrismaClientKnownRequestError &&
        err.code === 'P2002'
      )
        throw duplicateError();
      if (!(err instanceof AppError))
        this.logger.error({
          msg: 'saving uploaded image failed',
          auctionId,
          imageId,
          error: (err as Error).message,
        });
      throw err;
    }
    if (replacedPrefix)
      await this.cleanupNow(replacedPrefix, provider, 'image_replaced');
    this.metrics.mediaUploads.inc({ result: 'ok' });
    this.logger.log({
      msg: 'image stored',
      auctionId,
      imageId,
      provider,
      inputBytes: processed.inputBytes,
      storedBytes: row.bytes,
      ms: Math.round(performance.now() - started),
    });
    return toImageDto(row);
  }

  private async assertNotDuplicate(
    auctionId: string,
    contentHash: string,
    exceptId?: string,
  ) {
    const dup = await this.prisma.listingMedia.findFirst({
      where: {
        auctionId,
        contentHash,
        ...(exceptId ? { id: { not: exceptId } } : {}),
      },
      select: { id: true },
    });
    if (dup) throw duplicateError(dup.id);
  }

  // ───────────── Ordering / cover / delete ─────────────

  async reorder(
    auth: AuthContext,
    auctionId: string,
    imageIds: string[],
  ): Promise<ImageDto[]> {
    await this.mutate(
      auth,
      auctionId,
      'auction.image.reorder',
      async (tx, rows) => {
        const current = new Set(rows.map((r) => r.id));
        if (
          imageIds.length !== rows.length ||
          new Set(imageIds).size !== imageIds.length ||
          imageIds.some((id) => !current.has(id))
        )
          throw Errors.badRequest(
            'INVALID_IMAGE_ORDER',
            'imageIds must list every image of this listing exactly once.',
          );
        await this.writeOrder(tx, auctionId, imageIds);
        return { order: imageIds };
      },
    );
    return this.dtos(auctionId);
  }

  /** The cover is always the first image, so making one primary moves it to the front. */
  async setPrimary(
    auth: AuthContext,
    auctionId: string,
    imageId: string,
  ): Promise<ImageDto[]> {
    await this.mutate(
      auth,
      auctionId,
      'auction.image.primary',
      async (tx, rows) => {
        if (!rows.some((r) => r.id === imageId)) throw Errors.notFound('Image');
        const order = [
          imageId,
          ...rows.map((r) => r.id).filter((id) => id !== imageId),
        ];
        await this.writeOrder(tx, auctionId, order);
        return { imageId };
      },
    );
    return this.dtos(auctionId);
  }

  async remove(
    auth: AuthContext,
    auctionId: string,
    imageId: string,
  ): Promise<ImageDto[]> {
    let removed: { prefix: string; storage: 'R2' | 'LOCAL' } | null = null;
    await this.mutate(
      auth,
      auctionId,
      'auction.image.delete',
      async (tx, rows) => {
        const target = rows.find((r) => r.id === imageId);
        if (!target) throw Errors.notFound('Image');
        await tx.listingMedia.delete({ where: { id: imageId } });
        // Objects are deleted only after this commits; the task guarantees it happens.
        if (target.storageKeyPrefix) {
          removed = {
            prefix: target.storageKeyPrefix,
            storage: target.storage as 'R2' | 'LOCAL',
          };
          await this.scheduleCleanup(
            tx,
            removed.prefix,
            removed.storage,
            'image_deleted',
          );
        }
        const rest = rows.filter((r) => r.id !== imageId).map((r) => r.id);
        if (rest.length) await this.writeOrder(tx, auctionId, rest);
        return { imageId };
      },
    );
    const r = removed as { prefix: string; storage: 'R2' | 'LOCAL' } | null;
    if (r && this.storage.enabled && r.storage === this.storage.provider)
      await this.cleanupNow(r.prefix, r.storage, 'image_deleted');
    return this.dtos(auctionId);
  }

  private async mutate(
    auth: AuthContext,
    auctionId: string,
    action: string,
    fn: (
      tx: Tx,
      rows: Awaited<ReturnType<AuctionImagesService['rows']>>,
    ) => Promise<Record<string, unknown>>,
  ) {
    const access = await this.assertCanManage(auth, auctionId);
    await this.prisma.$transaction(async (tx) => {
      await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtextextended(${`media:${auctionId}`}, 0))`;
      await this.assertCanManage(auth, auctionId, tx);
      const metadata = await fn(tx, await this.rows(auctionId, tx));
      await this.audit.record(
        {
          actorId: auth.userId,
          action,
          entityType: 'auction',
          entityId: auctionId,
          metadata: {
            ...metadata,
            ...(access.asAdmin ? { asAdmin: true } : {}),
          },
        },
        tx,
      );
    });
  }

  /**
   * Rewrites positions 0..n-1 in the given order; the first image becomes the cover.
   * Two phases because (auctionId, position) is unique and not deferrable: first move
   * every row out of the way, then assign final positions.
   */
  private async writeOrder(tx: Tx, auctionId: string, ids: string[]) {
    await tx.$executeRaw`
      UPDATE listing_media SET position = position + 100000, "isPrimary" = false
      WHERE "auctionId" = ${auctionId}::uuid`;
    for (const [position, id] of ids.entries())
      await tx.listingMedia.update({
        where: { id },
        data: { position, isPrimary: position === 0 },
      });
  }

  // ───────────── Object cleanup ─────────────

  private async scheduleCleanup(
    tx: Tx,
    keyPrefix: string,
    storage: 'R2' | 'LOCAL',
    reason: string,
  ) {
    const now = await this.prisma.dbNow(tx);
    await tx.mediaCleanupTask.upsert({
      where: { keyPrefix },
      create: { keyPrefix, storage, reason, runAfter: now },
      update: { reason, runAfter: now },
    });
  }

  /**
   * Deletes every variant under `prefix` now. On success the cleanup task is removed; on
   * failure it is (re)scheduled for MediaCleanupWorker. Never throws.
   */
  async cleanupNow(keyPrefix: string, storage: 'R2' | 'LOCAL', reason: string) {
    try {
      await this.storage.deleteMany(variantKeys(keyPrefix));
      await this.prisma.mediaCleanupTask.deleteMany({ where: { keyPrefix } });
    } catch (err) {
      this.logger.warn({
        msg: 'object cleanup deferred',
        keyPrefix,
        reason,
        error: (err as Error).message?.slice(0, 200),
      });
      await this.prisma.mediaCleanupTask
        .upsert({
          where: { keyPrefix },
          create: {
            keyPrefix,
            storage,
            reason,
            runAfter: new Date(Date.now() + 60_000),
            lastError: String((err as Error).message).slice(0, 500),
          },
          update: {
            reason,
            runAfter: new Date(Date.now() + 60_000),
            lastError: String((err as Error).message).slice(0, 500),
          },
        })
        .catch((e: unknown) =>
          this.logger.error({
            msg: 'could not record cleanup task',
            keyPrefix,
            error: (e as Error).message,
          }),
        );
    }
  }
}

function duplicateError(imageId?: string) {
  return Errors.conflict(
    'DUPLICATE_IMAGE',
    'This photo is already part of the listing.',
    imageId ? { imageId } : undefined,
  );
}

/** For error messages only; file names are never used as storage keys. */
function displayName(name: string): string {
  return name.replace(/[^\w.\- ()]/g, '_').slice(0, 100) || 'file';
}
